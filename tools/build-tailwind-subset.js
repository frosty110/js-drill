#!/usr/bin/env node
// ============================================================================
//  tools/build-tailwind-subset.js — compile Tailwind ONCE, here, not on phones
// ============================================================================
// index.html used to load https://cdn.tailwindcss.com, which is not a
// stylesheet — it is the Tailwind COMPILER. Every visitor downloaded it,
// it scanned the live DOM, generated CSS at runtime, and injected it. On the
// phone that ~80% of this app's study time happens on (PROFILE.md), that is
// the single most expensive thing on the boot path, and it is spent producing
// a stylesheet that is identical for every user on every load.
//
// It also could not be cached offline. The service worker bypasses
// cross-origin requests, so an offline cold start rendered the app unstyled —
// service-worker.js said so in its own header ("v2 will vendor the CDN assets
// for true cold-start offline"). And the tag carried no integrity hash and no
// version pin, so whatever cdn.tailwindcss.com served was what executed.
//
// Measured against the codebase, all of that bought 119 utility classes.
//
// So: compile them here, commit the result, ship a plain <link>. Same version
// the CDN served (3.4.10), same Ink & Amber palette (tools/tailwind-theme.js),
// same preflight — css/01-base.css has no reset of its own and depends on it.
//
//   node tools/build-tailwind-subset.js           # regenerate css/00-tailwind.css
//   node tools/check-tailwind-subset.js           # verify it covers what's used
//
// Regenerating needs `npm i` (tailwindcss is a devDependency). VERIFYING does
// not — the check is plain Node over the committed file, so CI stays
// dependency-free the way .github/workflows/checks.yml requires.
const fs = require('fs');
const os = require('os');
const path = require('path');
const { execFileSync } = require('child_process');

const ROOT = path.resolve(__dirname, '..');
const OUT = path.join(ROOT, 'css', '00-tailwind.css');
const { colors } = require('./tailwind-theme.js');

// The files Tailwind scans for class names. index.html is the only page that
// loads this stylesheet, but the JS that renders INTO it lives across js/ and
// ds/ — and those build markup as strings, so the class names are in the JS,
// not the HTML. Scanning wider than strictly necessary costs a few hundred
// bytes of unused rules and removes a whole category of "styled in dev,
// unstyled in prod" surprise.
const CONTENT = [
  path.join(ROOT, 'index.html'),
  path.join(ROOT, 'js/**/*.js'),
  path.join(ROOT, 'ds/**/*.js')
];

function build() {
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'tw-subset-'));
  const configPath = path.join(tmp, 'tailwind.config.js');
  const inputPath = path.join(tmp, 'input.css');

  fs.writeFileSync(configPath, `module.exports = {
  content: ${JSON.stringify(CONTENT)},
  theme: { extend: { colors: ${JSON.stringify(colors)} } },
  corePlugins: { preflight: true }
};
`);

  // Preflight is REQUIRED, not optional: css/01-base.css sets a font and a
  // background and nothing else, so the app has always inherited its margin
  // reset, its `button { font: inherit }`, its `img { display: block }` and
  // the rest from Tailwind's base layer. Dropping it would restyle every
  // heading, list and button on the page.
  fs.writeFileSync(inputPath, '@tailwind base;\n@tailwind components;\n@tailwind utilities;\n');

  const bin = path.join(ROOT, 'node_modules', '.bin', 'tailwindcss');
  if (!fs.existsSync(bin)) {
    console.error(
      'tailwindcss is not installed. This is the GENERATOR, which needs it:\n' +
      '  npm install\n' +
      'Verifying the committed output does not — use tools/check-tailwind-subset.js.');
    process.exit(2);
  }

  const css = execFileSync(bin, ['-c', configPath, '-i', inputPath], {
    cwd: ROOT, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe']
  });

  const banner = `/* GENERATED by tools/build-tailwind-subset.js — DO NOT EDIT BY HAND.
 *
 * The Tailwind utilities this app actually uses, compiled at build time from
 * tailwindcss@3.4.10 with the Ink & Amber palette in tools/tailwind-theme.js.
 * This replaced https://cdn.tailwindcss.com, which shipped the whole compiler
 * to every visitor and re-derived these same rules in the browser on every
 * load — unpinned, un-hashed, and impossible to cache offline.
 *
 * Includes Tailwind's preflight: css/01-base.css has no reset of its own.
 *
 * Regenerate:  node tools/build-tailwind-subset.js   (needs npm install)
 * Verify:      node tools/check-tailwind-subset.js   (no dependencies)
 */
`;

  fs.writeFileSync(OUT, banner + css);
  fs.rmSync(tmp, { recursive: true, force: true });

  const kb = (fs.statSync(OUT).size / 1024).toFixed(1);
  const rules = (css.match(/^\./gm) || []).length;
  console.log(`✓ wrote css/00-tailwind.css — ${kb} KB, ${rules} class rules`);
  console.log('  (replaces a ~400 KB runtime compiler on every page load)');
}

build();
