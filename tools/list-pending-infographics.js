#!/usr/bin/env node
// Print the art brief for every registered infographic sheet whose PNG is not
// on disk yet.
//
// Why this exists: artwork for new design problems is produced out-of-band, so
// `validate-system-design.js` is deliberately left red until the PNGs land —
// the failing run IS the to-do list. But a validator error only says "missing
// <path>"; it doesn't say what the sheet is supposed to teach. This reads the
// authored specs in infographic-sets.json and emits, per missing sheet, the
// exact output path, the required pixel dimensions, and the full authored copy
// (purpose, description, numbered flow, operating numbers, priorities,
// trade-offs) that the sheet has to render.
//
// Text is authored before pixels (data/system-design/INFOGRAPHIC-AUTHORING.md),
// so everything below is the source of truth the image must match.
//
// Usage:
//   node tools/list-pending-infographics.js            # human-readable brief
//   node tools/list-pending-infographics.js --paths    # just the missing paths
//   node tools/list-pending-infographics.js --json     # machine-readable

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const SD = path.join(ROOT, 'data', 'system-design');
const INFOGRAPHICS = path.join(ROOT, 'assets', 'system-design', 'infographics');

const sets = JSON.parse(fs.readFileSync(path.join(SD, 'infographic-sets.json'), 'utf8')).sets || {};
const plan = JSON.parse(fs.readFileSync(path.join(SD, 'infographic-plan.json'), 'utf8')).lessons || {};

const mode = process.argv[2] || '';
const missing = [];

for (const [key, set] of Object.entries(sets)) {
  const [topic, lesson] = key.split('/');
  for (const item of set.items || []) {
    const rel = `${topic}/${lesson}/${item.id}.png`;
    if (fs.existsSync(path.join(INFOGRAPHICS, rel))) continue;
    missing.push({
      lesson: key,
      setTitle: set.title,
      pending: plan[key] && plan[key].pending === true,
      // `renderer: diagram-v1` sheets are produced by the generator; anything
      // else is hand-drawn and has to be supplied.
      handDrawn: item.renderer !== 'diagram-v1',
      path: `assets/system-design/infographics/${rel}`,
      width: item.width, height: item.height,
      ...item
    });
  }
}

if (mode === '--json') { console.log(JSON.stringify(missing, null, 2)); process.exit(0); }
if (mode === '--paths') { missing.forEach(m => console.log(m.path)); process.exit(0); }

if (!missing.length) {
  console.log('No pending infographics — every registered sheet has its PNG on disk.');
  process.exit(0);
}

const byLesson = new Map();
for (const m of missing) {
  if (!byLesson.has(m.lesson)) byLesson.set(m.lesson, []);
  byLesson.get(m.lesson).push(m);
}

console.log(`\n${missing.length} pending infographic sheet(s) across ${byLesson.size} lesson(s).`);
console.log('Each sheet below must land at its exact path AND exact pixel dimensions —');
console.log('the validator compares both, and a mismatch fails the same as a missing file.\n');

for (const [lesson, items] of byLesson) {
  console.log('='.repeat(78));
  console.log(`${lesson} — ${items[0].setTitle}`);
  console.log(`${items.length} sheet(s), in this order\n`);
  items.forEach((m, i) => {
    console.log(`  ${i + 1}. ${m.title}   [${m.kind}]${m.handDrawn ? '' : '   (generated by diagram-v1, not hand-drawn)'}`);
    console.log(`     path   ${m.path}`);
    console.log(`     size   ${m.width} x ${m.height} px (portrait, exact)`);
    console.log(`     job    ${m.purpose}`);
    console.log(`     idea   ${m.description}`);
    console.log(`     flow`);
    (m.flow || []).forEach(s => console.log(`            ${s.step}. ${s.title} — ${s.detail}`));
    console.log(`     numbers`);
    (m.numbers || []).forEach(n => console.log(`            ${n.label}: ${n.value} — ${n.detail}`));
    console.log(`     priorities   ${(m.priorities || []).join(' · ')}`);
    console.log(`     trade-offs`);
    (m.tradeoffs || []).forEach(t => console.log(`            - ${t}`));
    console.log('');
  });
}

console.log('='.repeat(78));
console.log('Reference for visual grammar: assets/system-design/infographics/design-problems/p01/');
console.log('(hand-authored pilot set — match its density, legend style and section rhythm).');
console.log('Authoring rules: data/system-design/INFOGRAPHIC-AUTHORING.md\n');
